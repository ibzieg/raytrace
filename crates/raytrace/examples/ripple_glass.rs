//! Generates `ripple_glass.obj`: a glass pane with water-drop ripples on its
//! front face and a flat back, closed by side walls so refracted rays enter
//! and leave the solid.
//!
//!     cargo run -p raytrace --example ripple_glass -- assets/objects
//!
//! The pane spans -1..1 in X and Y, faces +Z, and is centered on z = 0.

use std::f64::consts::TAU;
use std::fmt::Write as _;
use std::path::PathBuf;

/// Grid cells along each side of the faces.
const N: usize = 200;
const HALF_THICKNESS: f64 = 0.06;

/// (center x, center y, amplitude, wavelength, decay distance)
const DROPS: [(f64, f64, f64, f64, f64); 3] = [
    (-0.30, 0.25, 0.010, 0.34, 1.0),
    (0.45, -0.35, 0.006, 0.26, 0.7),
    (0.55, 0.60, 0.004, 0.20, 0.5),
];

/// Ripple height above the front face.
fn height(x: f64, y: f64) -> f64 {
    let ripples: f64 = DROPS
        .iter()
        .map(|&(cx, cy, amp, wavelength, decay)| {
            let r = (x - cx).hypot(y - cy);
            amp * (TAU * r / wavelength).cos() * (-r / decay).exp()
        })
        .sum();
    // Fade out near the rim so the side walls stay short and even.
    let edge = (1.0 - x.abs().max(y.abs())).clamp(0.0, 0.1) / 0.1;
    ripples * edge * edge * (3.0 - 2.0 * edge)
}

fn main() -> std::io::Result<()> {
    let dir = std::env::args().nth(1).map_or_else(|| PathBuf::from("."), PathBuf::from);
    let coord = |i: usize| -1.0 + 2.0 * i as f64 / N as f64;
    let row = N + 1;
    // 1-based OBJ indices of the front and back grid vertices.
    let front = |i: usize, j: usize| 1 + j * row + i;
    let back = |i: usize, j: usize| 1 + row * row + j * row + i;

    let mut obj = String::new();
    writeln!(obj, "# Rippled glass pane, generated by crates/raytrace/examples/ripple_glass.rs").unwrap();
    writeln!(obj, "mtllib ripple_glass.mtl\nusemtl ripple_glass").unwrap();
    for j in 0..=N {
        for i in 0..=N {
            let (x, y) = (coord(i), coord(j));
            writeln!(obj, "v {x:.5} {y:.5} {:.6}", HALF_THICKNESS + height(x, y)).unwrap();
        }
    }
    for j in 0..=N {
        for i in 0..=N {
            writeln!(obj, "v {:.5} {:.5} {:.6}", coord(i), coord(j), -HALF_THICKNESS).unwrap();
        }
    }

    // Counter-clockwise seen from outside, so normals point out.
    writeln!(obj, "s 1").unwrap();
    for j in 0..N {
        for i in 0..N {
            let (a, b, c, d) = (front(i, j), front(i + 1, j), front(i + 1, j + 1), front(i, j + 1));
            writeln!(obj, "f {a} {b} {c}\nf {a} {c} {d}").unwrap();
        }
    }
    writeln!(obj, "s 2").unwrap();
    for j in 0..N {
        for i in 0..N {
            let (a, b, c, d) = (back(i, j), back(i + 1, j), back(i + 1, j + 1), back(i, j + 1));
            writeln!(obj, "f {a} {c} {b}\nf {a} {d} {c}").unwrap();
        }
    }

    // Side walls, walking the rim counter-clockwise seen from +Z.
    writeln!(obj, "s off").unwrap();
    let rim: Vec<(usize, usize)> = (0..N)
        .map(|i| (i, 0))
        .chain((0..N).map(|j| (N, j)))
        .chain((0..N).map(|i| (N - i, N)))
        .chain((0..N).map(|j| (0, N - j)))
        .collect();
    for k in 0..rim.len() {
        let (i0, j0) = rim[k];
        let (i1, j1) = rim[(k + 1) % rim.len()];
        let (f0, f1, b0, b1) = (front(i0, j0), front(i1, j1), back(i0, j0), back(i1, j1));
        writeln!(obj, "f {f0} {b0} {b1} {f1}").unwrap();
    }

    let mtl = "\
# Clear glass for ripple_glass.obj.
newmtl ripple_glass
Ka 0.0 0.0 0.0
Kd 0.9 0.95 1.0
Ks 1.0 1.0 1.0
Ns 300.0
Ni 1.5
Ir 0.06
It 0.92
";
    std::fs::write(dir.join("ripple_glass.obj"), obj)?;
    std::fs::write(dir.join("ripple_glass.mtl"), mtl)?;
    eprintln!("wrote ripple_glass.obj and ripple_glass.mtl to {}", dir.display());
    Ok(())
}
